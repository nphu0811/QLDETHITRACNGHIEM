DECLARE @Removed TABLE (MAMH NCHAR(5), MALOP NCHAR(15), LAN SMALLINT);

BEGIN TRY
    BEGIN TRANSACTION;

    DELETE dk
    OUTPUT deleted.MAMH, deleted.MALOP, deleted.LAN INTO @Removed
    FROM dbo.GIAOVIEN_DANGKY dk
    INNER JOIN @Seed s
        ON dk.MAMH = s.MAMH AND dk.MALOP = s.MALOP AND dk.LAN = s.LAN
    WHERE dk.MAGV = s.MAGV
      AND dk.TRINHDO = s.TRINHDO
      AND dk.NGAYTHI = s.NGAYTHI
      AND dk.SOCAUTHI = s.SOCAUTHI
      AND dk.THOIGIAN = s.THOIGIAN
      AND NOT EXISTS (
          SELECT 1 FROM dbo.BANGDIEM bd
          INNER JOIN dbo.SINHVIEN sv ON sv.MASV = bd.MASV
          WHERE sv.MALOP = dk.MALOP
            AND bd.MAMH = dk.MAMH AND bd.LAN = dk.LAN
      );

    COMMIT TRANSACTION;

    SELECT COUNT(*) AS RemovedCount FROM @Removed;
    SELECT RTRIM(MAMH) AS MAMH, RTRIM(MALOP) AS MALOP, LAN
    FROM @Removed ORDER BY MALOP, MAMH, LAN;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
