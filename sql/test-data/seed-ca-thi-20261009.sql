DECLARE @Seed TABLE (
    MAGV NCHAR(8), MAMH NCHAR(5), MALOP NCHAR(15),
    TRINHDO CHAR(1), NGAYTHI DATETIME, LAN SMALLINT,
    SOCAUTHI SMALLINT, THOIGIAN SMALLINT
);

