-- Chạy trong database kiểm thử riêng; toàn bộ fixture nằm trong transaction.
SET NOCOUNT ON;
IF OBJECT_ID('dbo.SP_MoBaiThi') IS NULL
    THROW 51000, N'ASSERT: thiếu SP_MoBaiThi để mở và phục hồi bài thi.', 1;
GO

IF DB_NAME() <> N'THITRACNGHIEM_VERIFY'
    THROW 51000, N'Test chỉ được chạy trong THITRACNGHIEM_VERIFY.', 1;
SET NOCOUNT ON;

-- Lọc môn/ngày/lần độc lập, ngày tương lai vẫn được liệt kê nhưng chưa được bắt đầu.
CREATE TABLE #Ca (MAMH NVARCHAR(5), TENMH NVARCHAR(50), NGAYTHI DATE, LAN SMALLINT,
    TRINHDO VARCHAR(1), SOCAUTHI SMALLINT, THOIGIAN SMALLINT);
DECLARE @HomNay DATE = CONVERT(DATE, DATEADD(HOUR, 7, SYSUTCDATETIME()));
INSERT #Ca EXEC dbo.SP_LayCaThiSinhVien N'VFY00001', NULL, @HomNay, NULL;
IF (SELECT COUNT(*) FROM #Ca) <> 2 THROW 51000, N'ASSERT: lọc riêng ngày thi.', 1;
DELETE #Ca;
INSERT #Ca EXEC dbo.SP_LayCaThiSinhVien N'VFY00001', NULL, NULL, 2;
IF (SELECT COUNT(*) FROM #Ca) <> 1 THROW 51000, N'ASSERT: lọc riêng lần thi.', 1;
BEGIN TRY
    EXEC dbo.SP_MoBaiThi N'VFY00001', N'VFY01', 2;
    THROW 51000, N'ASSERT: phải từ chối ngày tương lai.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 50002 THROW;
END CATCH;
BEGIN TRY
    EXEC dbo.SP_MoBaiThi N'VFY00001', N'VFY02', 1;
    THROW 51000, N'ASSERT: phải từ chối bộ đề thiếu câu.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 50006 THROW;
END CATCH;
IF EXISTS (SELECT 1 FROM dbo.TRANGTHAITHI) THROW 51000, N'ASSERT: lỗi phải rollback.', 1;

EXEC dbo.SP_MoBaiThi N'VFY00001', N'VFY01', 1;
IF (SELECT COUNT(*) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001') <> 10
    THROW 51000, N'ASSERT: bài phải có đúng 10 câu.', 1;
IF (SELECT COUNT(*) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001' AND TRINHDOCAU = 'B') <> 7
    OR (SELECT COUNT(*) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001' AND TRINHDOCAU = 'C') <> 3
    THROW 51000, N'ASSERT: tỷ lệ 7 B / 3 C.', 1;
IF (SELECT COUNT(DISTINCT CAUHOI) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001') <> 10
    THROW 51000, N'ASSERT: câu hỏi không được trùng.', 1;
SELECT * INTO #BanDau FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001';

EXEC dbo.SP_LuuTienDoThi N'VFY00001', N'VFY01', 1, 1, N'A', 1;
EXEC dbo.SP_LuuTienDoThi N'VFY00001', N'VFY01', 1, 2, N'B', 2;
EXEC dbo.SP_LuuTienDoThi N'VFY00001', N'VFY01', 1, 3, N'A', 3;
EXEC dbo.SP_LuuTienDoThi N'VFY00001', N'VFY01', 1, 3, N'', 3;
EXEC dbo.SP_LuuTienDoThi N'VFY00001', N'VFY01', 1, 4, NULL, 4;
EXEC dbo.SP_MoBaiThi N'VFY00001', N'VFY01', 1;
IF EXISTS (SELECT THUTU, CAUHOI, BATDAU, HANKETTHUC FROM #BanDau
    EXCEPT SELECT THUTU, CAUHOI, BATDAU, HANKETTHUC FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001')
    THROW 51000, N'ASSERT: resume không đổi đề/hạn giờ.', 1;
IF EXISTS (SELECT 1 FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001' AND CAUDANGXEM <> 4)
    OR (SELECT CAUTRALOI FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001' AND THUTU = 1) <> N'A'
    OR (SELECT CAUTRALOI FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001' AND THUTU = 3) <> N''
    THROW 51000, N'ASSERT: giữ lựa chọn/vị trí và xóa đáp án.', 1;

-- Đổi ngày ca trong khi đang thi: bài đang làm vẫn phải xuất hiện.
UPDATE dbo.GIAOVIEN_DANGKY SET NGAYTHI = DATEADD(DAY, -1, @HomNay) WHERE MAMH = N'VFY01' AND LAN = 1;
UPDATE dbo.TRANGTHAITHI SET NGAYTHI = DATEADD(DAY, -1, @HomNay) WHERE MASV = N'VFY00001';
DELETE #Ca;
INSERT #Ca EXEC dbo.SP_LayCaThiSinhVien N'VFY00001';
IF NOT EXISTS (SELECT 1 FROM #Ca WHERE MAMH = N'VFY01' AND LAN = 1)
    THROW 51000, N'ASSERT: bài đang làm không mất khi qua ngày.', 1;
BEGIN TRY
    EXEC dbo.SP_MoBaiThi N'VFY00002', N'VFY01', 1;
    THROW 51000, N'ASSERT: phải từ chối bắt đầu mới ở ngày quá khứ.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 50002 THROW;
END CATCH;

-- Nếu ghi chi tiết thất bại thì điểm không được ghi và trạng thái không được xóa.
ALTER TABLE dbo.CHITIETBAITHI WITH NOCHECK ADD CONSTRAINT CK_TestRollback CHECK (CAUTRALOI = N'X');
BEGIN TRY
    EXEC dbo.SP_NopBaiThi N'VFY00001', N'VFY01', 1;
    THROW 51000, N'ASSERT: fixture phải làm lỗi ghi chi tiết.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 547 THROW;
END CATCH;
ALTER TABLE dbo.CHITIETBAITHI DROP CONSTRAINT CK_TestRollback;
IF EXISTS (SELECT 1 FROM dbo.BANGDIEM WHERE MASV = N'VFY00001')
    OR (SELECT COUNT(*) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001') <> 10
    THROW 51000, N'ASSERT: nộp lỗi phải rollback cả điểm và trạng thái.', 1;

-- Thay bộ đề không thay bản chụp bài đã mở.
UPDATE dbo.BODE SET NOIDUNG = N'Đã sửa', DAP_AN = 'D';
UPDATE dbo.TRANGTHAITHI SET HANKETTHUC = DATEADD(SECOND, -1, SYSUTCDATETIME()) WHERE MASV = N'VFY00001';
BEGIN TRY
    EXEC dbo.SP_LuuTienDoThi N'VFY00001', N'VFY01', 1, 2, N'A', 2;
    THROW 51000, N'ASSERT: phải từ chối đáp án sau hạn giờ.', 1;
END TRY
BEGIN CATCH
    IF ERROR_NUMBER() <> 50003 THROW;
END CATCH;
EXEC dbo.SP_MoBaiThi N'VFY00001', N'VFY01', 1;
EXEC dbo.SP_NopBaiThi N'VFY00001', N'VFY01', 1;
IF (SELECT COUNT(*) FROM dbo.BANGDIEM WHERE MASV = N'VFY00001') <> 1
    OR (SELECT DIEM FROM dbo.BANGDIEM WHERE MASV = N'VFY00001') <> 1.0
    OR (SELECT COUNT(*) FROM dbo.CHITIETBAITHI WHERE MASV = N'VFY00001') <> 10
    OR EXISTS (SELECT 1 FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00001')
    THROW 51000, N'ASSERT: tự nộp, chấm 1/10, lưu chi tiết và xóa trạng thái.', 1;
IF EXISTS (SELECT CAUHOI, NOIDUNG, DAP_AN FROM #BanDau
    EXCEPT SELECT CAUHOI, NOIDUNG, DAP_AN FROM dbo.CHITIETBAITHI WHERE MASV = N'VFY00001')
    THROW 51000, N'ASSERT: lưu nguyên bản chụp.', 1;
DELETE #Ca;
INSERT #Ca EXEC dbo.SP_LayCaThiSinhVien N'VFY00001';
IF EXISTS (SELECT 1 FROM #Ca WHERE MAMH = N'VFY01' AND LAN = 1)
    THROW 51000, N'ASSERT: không liệt kê lại bài đã nộp.', 1;

-- Trình độ C: tất cả C. Nộp trắng vẫn ghi 0 điểm.
UPDATE dbo.GIAOVIEN_DANGKY SET NGAYTHI = @HomNay, TRINHDO = 'C' WHERE MAMH = N'VFY01' AND LAN = 1;
EXEC dbo.SP_MoBaiThi N'VFY00002', N'VFY01', 1;
IF (SELECT COUNT(*) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00002' AND TRINHDOCAU = 'C') <> 10
    THROW 51000, N'ASSERT: C phải lấy toàn bộ C.', 1;
EXEC dbo.SP_NopBaiThi N'VFY00002', N'VFY01', 1;
IF (SELECT DIEM FROM dbo.BANGDIEM WHERE MASV = N'VFY00002') <> 0
    THROW 51000, N'ASSERT: nộp trắng là 0 điểm.', 1;

UPDATE dbo.GIAOVIEN_DANGKY SET NGAYTHI = @HomNay WHERE MAMH = N'VFY01' AND LAN = 2;
EXEC dbo.SP_MoBaiThi N'VFY00002', N'VFY01', 2;
IF (SELECT COUNT(*) FROM dbo.TRANGTHAITHI WHERE MASV = N'VFY00002' AND TRINHDOCAU = 'A') <> 7
    THROW 51000, N'ASSERT: A phải lấy 7 A / 3 thấp hơn.', 1;
PRINT N'PASS SQL: lọc độc lập, ngày, 7/3, resume, xóa lựa chọn, deadline, rollback, snapshot, nộp idempotent.';
GO
