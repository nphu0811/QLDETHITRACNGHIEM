-- Chỉ dùng database kiểm thử. Không được chạy trong database ứng dụng.
IF DB_NAME() <> N'THITRACNGHIEM_VERIFY'
    THROW 51000, N'Fixture chỉ được chạy trong THITRACNGHIEM_VERIFY.', 1;
SET NOCOUNT ON;
IF OBJECT_ID('dbo.BANGDIEM') IS NULL
BEGIN
SELECT TOP (0) * INTO dbo.BANGDIEM FROM THITRACNGHIEM.dbo.BANGDIEM;
ALTER TABLE dbo.BANGDIEM ADD PRIMARY KEY (MASV, MAMH, LAN);
SELECT TOP (0) * INTO dbo.BODE FROM THITRACNGHIEM.dbo.BODE;
ALTER TABLE dbo.BODE ADD PRIMARY KEY (CAUHOI);
SELECT TOP (0) * INTO dbo.SINHVIEN FROM THITRACNGHIEM.dbo.SINHVIEN;
SELECT TOP (0) * INTO dbo.GIAOVIEN_DANGKY FROM THITRACNGHIEM.dbo.GIAOVIEN_DANGKY;
ALTER TABLE dbo.GIAOVIEN_DANGKY ADD PRIMARY KEY (MALOP, MAMH, LAN);
SELECT TOP (0) * INTO dbo.MONHOC FROM THITRACNGHIEM.dbo.MONHOC;
END;

-- Làm mới fixture để các phép kiểm tra có thể chạy lại.
IF OBJECT_ID('dbo.CHITIETBAITHI') IS NOT NULL DELETE dbo.CHITIETBAITHI;
IF OBJECT_ID('dbo.TRANGTHAITHI') IS NOT NULL DELETE dbo.TRANGTHAITHI;
DELETE dbo.BANGDIEM;
DELETE dbo.BODE;
DELETE dbo.GIAOVIEN_DANGKY;
DELETE dbo.SINHVIEN;
DELETE dbo.MONHOC;

INSERT dbo.SINHVIEN (MASV, HO, TEN, MALOP) VALUES (N'VFY00001', N'Kiểm', N'Thử', N'VFY_THI');
INSERT dbo.SINHVIEN (MASV, HO, TEN, MALOP) VALUES (N'VFY00002', N'Khác', N'Thử', N'VFY_THI');
INSERT dbo.MONHOC (MAMH, TENMH) VALUES (N'VFY01', N'Môn kiểm thử');
INSERT dbo.MONHOC (MAMH, TENMH) VALUES (N'VFY02', N'Môn chưa có câu');
INSERT dbo.GIAOVIEN_DANGKY (MAMH, MALOP, LAN, NGAYTHI, TRINHDO, SOCAUTHI, THOIGIAN)
VALUES (N'VFY01', N'VFY_THI', 1, CONVERT(DATE, DATEADD(HOUR, 7, SYSUTCDATETIME())), 'B', 10, 30),
       (N'VFY01', N'VFY_THI', 2, DATEADD(DAY, 1, CONVERT(DATE, DATEADD(HOUR, 7, SYSUTCDATETIME()))), 'A', 10, 30),
       (N'VFY02', N'VFY_THI', 1, CONVERT(DATE, DATEADD(HOUR, 7, SYSUTCDATETIME())), 'C', 10, 30);
DECLARE @i INT = 1;
WHILE @i <= 30
BEGIN
    INSERT dbo.BODE (CAUHOI, MAMH, TRINHDO, NOIDUNG, A, B, C, D, DAP_AN)
    VALUES (@i, N'VFY01', CASE WHEN @i <= 10 THEN 'A' WHEN @i <= 20 THEN 'B' ELSE 'C' END,
        N'Nội dung ' + CONVERT(NVARCHAR(10), @i), N'Đúng', N'Sai B', N'Sai C', N'Sai D', 'A');
    SET @i += 1;
END;
IF DATABASE_PRINCIPAL_ID('sv') IS NULL CREATE USER sv FOR LOGIN sv;
GO
